const fs=require('fs'),path=require('path');
const assessment=require('./lib/ally-role-assessment.cjs');
const wrapper=`
(function(){
 const base=allyReview;
 allyReview=function(type,evolved){
  const html=base(type,evolved),d=data.units[type];
  if(!d||(d.hiddenAbility&&!codexWiki&&!futureOpen()))return html;
  const s=codexReviewStats(type,evolved),v=allyRoleAssessment(type,s,html);
  const escape=t=>String(t).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const add='<b>'+(s.trueForm?'3진 평가':'평가')+': '+escape(v.role)+'.</b> '+[v.strength,v.caution,v.use].map(escape).join(' ');
  return html.replace(/<\\/section>\\s*$/,'<p class="codex-verdict">'+add+'</p></section>');
 };
})();
`;
fs.writeFileSync(path.resolve(__dirname,'../codex-verdict.js'),'// Generated by scripts/make-codex-verdict.cjs. Current review and role; no tier labels.\n'+assessment.toString()+'\n'+wrapper);
